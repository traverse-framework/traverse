#!/usr/bin/env node
/**
 * Write src/packageVersion.generated.ts from package.json so release evidence
 * cannot drift from the published package version (issue #1654).
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
const version = pkg.version;
if (typeof version !== "string" || version.length === 0) {
  console.error("package.json is missing a non-empty version field");
  process.exit(1);
}

const outPath = join(root, "src", "packageVersion.generated.ts");
const contents = `/* eslint-disable */
// GENERATED by scripts/generate-package-version.mjs — do not edit by hand.
export const PACKAGE_VERSION = ${JSON.stringify(version)};
`;
writeFileSync(outPath, contents);
console.log(`wrote ${outPath} (PACKAGE_VERSION=${version})`);
