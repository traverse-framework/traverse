"""Shared rules for the 18 October 2026 pull request and CI snapshot.

Classification, first-run selection, and window bounds match the scripts that
produced ``data/first_runs.json``. Nothing in this module reads or writes the
network, and nothing writes a file.
"""

from __future__ import annotations

import json
import re
from datetime import datetime, timedelta, timezone
from pathlib import Path

SCRIPT_DIR = Path(__file__).resolve().parent
SNAPSHOT_DIR = SCRIPT_DIR.parent
DATA_DIR = SNAPSHOT_DIR / "data"
DEFAULT_FIRST_RUNS = DATA_DIR / "first_runs.json"

# Fixed UTC-6. On the dates in this snapshot that offset is Mountain Daylight Time.
MDT = timezone(timedelta(hours=-6))

WINDOW_30D = datetime(2026, 9, 18, tzinfo=MDT)
WINDOW_60D = datetime(2026, 8, 19, tzinfo=MDT)

AITR = re.compile(
    r"co-authored-by:\s*(claude|cursor|copilot|codex|devin|openai|chatgpt|gemini)[^\n]*",
    re.I,
)
AIBODY = re.compile(
    r"generated with \[?claude code|generated with cursor|cursor agent|generated by (codex|copilot|devin)",
    re.I,
)
AIAUTH = re.compile(
    r"(noreply@anthropic\.com|cursoragent@cursor\.com|copilot|devin|codex)",
    re.I,
)

BRANCH_PREFIXES = frozenset({"codex", "claude", "cursor", "copilot", "devin"})
METADATA_CHECKS = frozenset(
    {
        "spec-alignment",
        "pr-hygiene",
        "cla / cla",
        "version-guard",
        "baseline / governance-baseline",
    }
)
FAIL_CONCLUSIONS = frozenset(
    {"failure", "timed_out", "startup_failure", "action_required"}
)

PULL_REQUEST_QUERY = """query($c:String){repository(owner:"traverse-framework",name:"traverse"){pullRequests(first:40,after:$c,orderBy:{field:CREATED_AT,direction:ASC}){totalCount pageInfo{hasNextPage endCursor} nodes{number title state createdAt mergedAt closedAt headRefName baseRefName isDraft additions deletions author{login __typename} mergedBy{login} labels(first:20){nodes{name}} body
 commits(first:100){totalCount nodes{commit{oid committedDate message authors(first:5){nodes{name email user{login}}} statusCheckRollup{state} checkSuites(first:20){nodes{conclusion status app{slug} workflowRun{workflow{name} event}}}}}}}}}}"""


def parse_time(value: str) -> datetime:
    """Parse an API timestamp and convert it to the fixed UTC-6 offset."""
    return datetime.fromisoformat(value.replace("Z", "+00:00")).astimezone(MDT)


def classify(pull: dict) -> tuple[str, list[str]]:
    """Return ``bot``, ``ai``, or ``unknown``, plus the markers that fired.

    ``ai`` is the agent-generated category. ``unknown`` means no marker fired.
    It is not a confirmation that a person wrote the pull request.
    """
    evidence: list[str] = []
    author = pull["author"] or {}
    if author.get("__typename") == "Bot":
        return "bot", ["author is Bot: " + author["login"]]
    head = pull["headRefName"]
    prefix = head.split("/")[0].lower() if "/" in head else ""
    if prefix in BRANCH_PREFIXES:
        evidence.append("branch:" + prefix)
    for label in pull["labels"]["nodes"]:
        if label["name"].lower().startswith("agent:"):
            evidence.append("label:" + label["name"])
    if AIBODY.search(pull["body"] or ""):
        evidence.append("body:generated-with")
    trailers: set[str] = set()
    authors: set[str] = set()
    for node in pull["commits"]["nodes"]:
        commit = node["commit"]
        for match in AITR.findall(commit["message"]):
            trailers.add(match.lower())
        for person in commit["authors"]["nodes"]:
            email = person["email"] or ""
            name = person["name"] or ""
            if AIAUTH.search(email) or AIAUTH.search(name):
                authors.add(person["email"])
    evidence.extend("trailer:" + trailer for trailer in sorted(trailers))
    evidence.extend("commit-author:" + email for email in sorted(authors))
    if evidence:
        return "ai", evidence
    return "unknown", []


def first_checked(pull: dict) -> tuple[str | None, str | None]:
    """Return the SHA and rollup state of the first commit that has a rollup."""
    commits = pull["commits"]["nodes"]
    for node in commits:
        rollup = node["commit"]["statusCheckRollup"]
        if rollup:
            return node["commit"]["oid"], rollup["state"]
    return None, None


def failure_names(check_runs: dict, statuses: dict) -> list[str]:
    """Names of failing checks on one saved REST response pair.

    Check runs contribute ``name`` when the conclusion is a failure conclusion.
    Commit statuses contribute ``status:`` plus the context when the state is
    ``failure`` or ``error``. This does not request another page. A
    ``total_count`` above 100 is rejected, matching the guard used when the
    snapshot was built.
    """
    total = check_runs["total_count"]
    if total > 100:
        raise RuntimeError(f"check-runs total_count {total} is above 100")
    names = sorted(
        run["name"]
        for run in check_runs["check_runs"]
        if run["conclusion"] in FAIL_CONCLUSIONS
    )
    names.extend(
        sorted(
            "status:" + status["context"]
            for status in statuses["statuses"]
            if status["state"] in ("failure", "error")
        )
    )
    return names


def category(row: dict) -> str | None:
    """Pass, pending, spec-alignment only, other metadata, or code/test/build.

    Rows with no rollup return None. An empty failing-check list on a failed
    rollup counts as code, test, or build (pull request 1664, cancelled job).
    """
    roll = row["roll"]
    if not roll:
        return None
    if roll == "SUCCESS":
        return "pass"
    if roll == "PENDING":
        return "pending"
    failed = set(row["fails"])
    if not failed:
        return "code"
    if failed == {"spec-alignment"}:
        return "sa_only"
    if failed <= METADATA_CHECKS:
        return "meta_only"
    return "code"


def load_json(path: Path):
    return json.loads(path.read_text(encoding="utf-8"))


def load_first_runs(path: Path | None = None) -> list[dict]:
    return load_json(path or DEFAULT_FIRST_RUNS)


def prepare_output(path: Path) -> Path:
    """Create the output directory. Callers may write only inside it."""
    path.mkdir(parents=True, exist_ok=True)
    resolved = path.resolve()
    if not resolved.is_dir():
        raise SystemExit(f"output is not a directory: {path}")
    return resolved


def write_json(output_dir: Path, name: str, payload) -> Path:
    """Write one JSON file whose name cannot escape ``output_dir``."""
    if name != Path(name).name or name in {"", ".", ".."}:
        raise SystemExit(f"refusing to write {name!r} outside the output directory")
    destination = output_dir / name
    destination.write_text(json.dumps(payload), encoding="utf-8")
    return destination
